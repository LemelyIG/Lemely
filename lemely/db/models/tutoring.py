#: index predicate (SPEC §a.2). Queries use
#: :func:`lemely.db.tutoring_predicates.listed_and_not_paused_sql` instead.
_LISTED_NOT_PAUSED = "listing_state = 'listed' AND paused_at IS NULL"


def _uuid_pk() -> Mapped[uuid.UUID]:
    """A ``uuid`` primary key generated by the database (SPEC §0: UUID v4 everywhere)."""
    return mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=sa.text("gen_random_uuid()"),
    )


def _created_at() -> Mapped[datetime]:
    """``created_at timestamptz NOT NULL DEFAULT now()`` for the append-only logs."""
    return mapped_column(
        sa.DateTime(timezone=True),
        server_default=sa.func.now(),
        nullable=False,
    )


