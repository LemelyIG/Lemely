class TutorAvailabilityRule(TimestampMixin, Base):
    """A weekly availability window, wall-clock in ``tutor_profiles.zone``.

    Minutes since local midnight, in 15-minute steps; a window crossing
    midnight is two rules. ``excl_tutor_availability_rules_no_overlap`` refuses
    two overlapping windows on the same weekday for one tutor, and its GiST
    index (leading ``tutor_profile_id``) serves per-tutor reads and the FK.
    """

    __tablename__ = "tutor_availability_rules"
    __table_args__ = (
        sa.CheckConstraint("iso_weekday BETWEEN 1 AND 7", name="iso_weekday_range"),
        sa.CheckConstraint(
            "start_minute BETWEEN 0 AND 1425 AND start_minute % 15 = 0",
            name="start_minute_range",
        ),
        sa.CheckConstraint(
            "end_minute BETWEEN 15 AND 1440 AND end_minute % 15 = 0 AND end_minute > start_minute",
            name="end_minute_range",
        ),
        ExcludeConstraint(
            ("tutor_profile_id", "="),
            ("iso_weekday", "="),
            (sa.text("int4range(start_minute, end_minute, '[)')"), "&&"),
            name="excl_tutor_availability_rules_no_overlap",
            using="gist",
        ),
        sa.Index(
            "ix_tutor_availability_rules_window",
            "iso_weekday",
            "start_minute",
            "end_minute",
            "tutor_profile_id",
        ),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    tutor_profile_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        sa.ForeignKey("tutor_profiles.id", ondelete="CASCADE"),
        nullable=False,
    )
    iso_weekday: Mapped[int] = mapped_column(sa.SmallInteger, nullable=False)
    start_minute: Mapped[int] = mapped_column(sa.SmallInteger, nullable=False)
    end_minute: Mapped[int] = mapped_column(sa.SmallInteger, nullable=False)


