"""ORM models for the tutoring marketplace (SPEC ``docs/tutoring/SPEC.md`` §a.2-§a.4).

Eighteen tables, created by migrations ``0045``-``0051`` (``0051`` adds the T6
upload-attempt log, T30 F30-5; SPEC §a.2 lists the other seventeen). The ORM declares
every constraint and index those migrations create, including the three GiST
exclusion constraints, so a database built with ``Base.metadata.create_all``
(about 88 test files build theirs that way) enforces the same rules as a
migrated one (SPEC §a.4, F2). ``tests/test_db_tutoring_schema.py`` compares the
two catalogues object by object.

**Constraint names.** ``NAMING_CONVENTION`` (``lemely/db/base.py``) prefixes
``ck_<table>_`` itself, so every ``CheckConstraint`` here passes the short name
(``name="first_name_len"`` becomes ``ck_tutor_profiles_first_name_len``).
Exclusion constraints, composite foreign keys and every index carry their full
name explicitly: the convention has no key for exclusions, and its ``fk`` key
would give the three foreign keys from ``tutor_reviews`` to ``tutor_bookings``
the same name.

**``btree_gist``.** The exclusion constraints compare ``uuid`` and ``smallint``
columns with ``=`` inside a GiST index, which needs the ``btree_gist``
extension. Migration ``0044`` installs it; for ``create_all`` databases the
``before_create`` listeners at the bottom of this module install it right
before either table that needs it is created.

**Deletion rule (SPEC §a, SC-21).** Safeguarding records never cascade away: a
user who owns a tutor profile or is the subject of a booking cannot be deleted
(``RESTRICT``), and tutor profiles are closed, never deleted.

**Timestamps.** Every table has ``created_at``/``updated_at`` through
:class:`TimestampMixin` unless SPEC §a.2 says otherwise: ``tutor_subjects`` has
none, and the five append-only logs (``tutor_approval_events``,
``tutoring_admin_access``, ``parent_link_events``, ``tutor_access_audit``,
``tutor_evidence_uploads``) have ``created_at`` only.
"""

