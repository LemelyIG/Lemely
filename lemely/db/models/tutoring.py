class TutorProfile(TimestampMixin, Base):
    """A teacher's tutor listing, 1:1 with a ``users`` row (ADR-T01).

    The service checks ``users.role = teacher`` at create. Public columns (SPEC
    §a.5): ``public_first_name``, ``public_last_initial``, ``headline``, the
    three mode flags, ``area_code``, ``indexable`` and the rating pair.
    ``rating_avg`` is generated by the database; ``rank_score`` is written by the
    service from ``core.tutor_ratings.bayesian_score`` in the same transaction as
    any rating change, and its default is the zero-review score.
    """

    __tablename__ = "tutor_profiles"
    __table_args__ = (
        sa.CheckConstraint(
            "char_length(btrim(public_first_name)) BETWEEN 1 AND 40", name="first_name_len"
        ),
        sa.CheckConstraint(
            sa.literal_column(
                "public_first_name !~ '[0-9./@:]' AND public_first_name !~ '[[:cntrl:]]'"
            ),
            name="first_name_chars",
        ),
        sa.CheckConstraint("char_length(public_last_initial) = 1", name="last_initial_len"),
        sa.CheckConstraint("char_length(btrim(headline)) >= 1", name="headline_not_blank"),
        sa.CheckConstraint("char_length(bio) <= 2000", name="bio_len"),
        sa.CheckConstraint(
            "char_length(qualification_note) <= 1000", name="qualification_note_len"
        ),
        sa.CheckConstraint("offers_virtual OR offers_in_person OR offers_other", name="has_mode"),
        sa.CheckConstraint("offers_other OR other_mode_note IS NULL", name="other_note"),
        sa.CheckConstraint("(listing_state = 'closed') = (closed_at IS NOT NULL)", name="closed"),
        sa.CheckConstraint("rating_count >= 0", name="rating_count_nonneg"),
        sa.CheckConstraint(
            "rating_sum BETWEEN rating_count AND 5 * rating_count", name="rating_sum_range"
        ),
        sa.UniqueConstraint("user_id", name="uq_tutor_profiles_user_id"),
        sa.Index(
            "ix_tutor_profiles_directory",
            sa.text("rank_score DESC"),
            "first_listed_at",
            "id",
            postgresql_where=sa.text(_LISTED_NOT_PAUSED),
        ),
        sa.Index(
            "ix_tutor_profiles_area_rank",
            "area_code",
            sa.text("rank_score DESC"),
            "first_listed_at",
            "id",
            postgresql_where=sa.text(_LISTED_NOT_PAUSED),
        ),
        sa.Index(
            "ix_tutor_profiles_rated",
            "rating_avg",
            postgresql_where=sa.text(f"{_LISTED_NOT_PAUSED} AND rating_count >= 3"),
        ),
        sa.Index(
            "ix_tutor_profiles_mode_virtual",
            sa.text("rank_score DESC"),
            "first_listed_at",
            "id",
            postgresql_where=sa.text(f"{_LISTED_NOT_PAUSED} AND offers_virtual"),
        ),
        sa.Index(
            "ix_tutor_profiles_mode_in_person",
            sa.text("rank_score DESC"),
            "first_listed_at",
            "id",
            postgresql_where=sa.text(f"{_LISTED_NOT_PAUSED} AND offers_in_person"),
        ),
        sa.Index(
            "ix_tutor_profiles_mode_other",
            sa.text("rank_score DESC"),
            "first_listed_at",
            "id",
            postgresql_where=sa.text(f"{_LISTED_NOT_PAUSED} AND offers_other"),
        ),
        sa.Index("ix_tutor_profiles_review_queue", "listing_state", "submitted_at", "id"),
    )

    id: Mapped[uuid.UUID] = _uuid_pk()
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        sa.ForeignKey("users.id", ondelete="RESTRICT"),
        nullable=False,
    )
    public_first_name: Mapped[str] = mapped_column(sa.String(40), nullable=False)
    public_last_initial: Mapped[str | None] = mapped_column(sa.String(1), nullable=True)
    headline: Mapped[str] = mapped_column(sa.String(160), nullable=False)
    bio: Mapped[str] = mapped_column(sa.Text, nullable=False, server_default=sa.text("''"))
    qualification_note: Mapped[str | None] = mapped_column(sa.Text, nullable=True)
    offers_virtual: Mapped[bool] = mapped_column(
        sa.Boolean, nullable=False, server_default=sa.false()
    )
    offers_in_person: Mapped[bool] = mapped_column(
        sa.Boolean, nullable=False, server_default=sa.false()
    )
    offers_other: Mapped[bool] = mapped_column(
        sa.Boolean, nullable=False, server_default=sa.false()
    )
    other_mode_note: Mapped[str | None] = mapped_column(sa.String(200), nullable=True)
    country_code: Mapped[str] = mapped_column(
        sa.CHAR(2), nullable=False, server_default=sa.text("'EG'")
    )
    area_code: Mapped[str] = mapped_column(sa.String(40), nullable=False)
    zone: Mapped[str] = mapped_column(
        sa.String(64), nullable=False, server_default=sa.text("'Africa/Cairo'")
    )
    listing_state: Mapped[TutorListingState] = mapped_column(
        sa.Enum(TutorListingState, name="tutorlistingstate"),
        nullable=False,
        server_default=sa.text("'draft'::tutorlistingstate"),
    )
    submitted_at: Mapped[datetime | None] = mapped_column(sa.DateTime(timezone=True))
    listed_at: Mapped[datetime | None] = mapped_column(sa.DateTime(timezone=True))
    first_listed_at: Mapped[datetime | None] = mapped_column(sa.DateTime(timezone=True))
    paused_at: Mapped[datetime | None] = mapped_column(sa.DateTime(timezone=True))
    closed_at: Mapped[datetime | None] = mapped_column(sa.DateTime(timezone=True))
    indexable: Mapped[bool] = mapped_column(sa.Boolean, nullable=False, server_default=sa.true())
    """Row 17: a public card is search-indexable by default; the tutor opts out."""
    documents_seen_at: Mapped[datetime | None] = mapped_column(sa.DateTime(timezone=True))
    rating_count: Mapped[int] = mapped_column(
        sa.Integer, nullable=False, server_default=sa.text("0")
    )
    """Distinct students with a counted review (SC-16)."""
    rating_sum: Mapped[int] = mapped_column(sa.Integer, nullable=False, server_default=sa.text("0"))
    rating_avg: Mapped[Decimal | None] = mapped_column(
        sa.Numeric(3, 2),
        sa.Computed(
            "CASE WHEN rating_count = 0 THEN NULL "
            "ELSE round(rating_sum::numeric / rating_count, 2) END",
            persisted=True,
        ),
    )
    rank_score: Mapped[Decimal] = mapped_column(
        sa.Numeric(7, 6), nullable=False, server_default=sa.text("4.000000")
    )


